// Ορθογραφικές κλάσεις σύγχυσης — ΔΕΔΟΜΕΝΑ, όχι phonological engine
// (PROJECT_SPEC κεφ. 4). Φάση 1: μόνο οι τέσσερις πρώτες κλάσεις.

// ΣΕΙΡΑ ΣΗΜΑΣΙΑΣ: το classForGrapheme επιστρέφει την ΠΡΩΤΗ κλάση που ταιριάζει.
// Οι κλάσεις των διαλυτικών μπαίνουν ΤΕΛΕΥΤΑΙΕΣ επίτηδες, ώστε το «οι» να
// μένει ερώτημα /i/ (ι-η-υ-ει-οι) και μόνο το «οϊ» να γίνεται ερώτημα
// διαλυτικών. Αλλιώς κάθε «οι» θα έβγαζε έξι επιλογές.
export const CONFUSION_CLASSES = {
  i: ['ι', 'η', 'υ', 'ει', 'οι'],
  o: ['ο', 'ω'],
  e: ['ε', 'αι'],
  u: ['ου'], // μόνο του — λέξεις με «ου» παίζουν σε συναρμολόγηση, όχι σε κενό

  // --- Διαλυτικά (NEXT-FIXES Β2) ---
  // Δύο φωνήεντα μαζί: διαβάζονται ΕΝΩΜΕΝΑ (δίψηφο) ή ΧΩΡΙΣΤΑ (διαλυτικά);
  // Κάθε κλάση έχει ακριβώς δύο μέλη — δυαδική ερώτηση, όχι εικασία.
  //   αϋπνία (α-ϋ) απέναντι στο αυτί (αυ)
  //   ευνοϊκό (ο-ϊ) απέναντι στο ποιος (οι)
  //   θεϊκός (ε-ϊ) απέναντι στο θείος (ει)
  //   μαϊμού (α-ϊ) απέναντι στο παιδί (αι)
  au: ['αυ', 'αϋ'],
  eu: ['ευ', 'εϋ'],
  oi_dia: ['οϊ', 'οι'],
  ei_dia: ['εϊ', 'ει'],
  ai_dia: ['αϊ', 'αι'],

  // --- Διπλά σύμφωνα (NEXT-FIXES Β3) ---
  // Ίδιος ήχος, διαφορετική γραφή: γέννηση ή γένηση; θάλασσα ή θάλασα;
  // Το κενό δέχεται υποψήφια ΔΙΑΦΟΡΕΤΙΚΟΥ ΜΗΚΟΥΣ — γι' αυτό το πλάτος του
  // κενού στην οθόνη υπολογίζεται από το ΦΑΡΔΥΤΕΡΟ υποψήφιο, όχι από τον
  // στόχο. Αλλιώς το ίδιο το κενό θα έλεγε την απάντηση.
  ll: ['λ', 'λλ'],
  mm: ['μ', 'μμ'],
  nn: ['ν', 'νν'],
  pp: ['π', 'ππ'],
  rr: ['ρ', 'ρρ'],
  ss: ['σ', 'σσ'],
  tt: ['τ', 'ττ'],
  kk: ['κ', 'κκ'],
  bb: ['β', 'ββ'],
  // γγ και γκ ακούγονται ΙΔΙΑ (άγγελος / αγκάλη) — αυτό είναι το πραγματικό
  // ερώτημα. Το «γ» απέναντι στο «γγ» δεν είναι: ακούγονται αλλιώς.
  gg: ['γγ', 'γκ']
};

// Κλάσεις που ΠΡΟΕΠΙΛΕΓΟΝΤΑΙ στο Parent Mode.
//
// Έξω μένουν δύο ομάδες, για διαφορετικό λόγο η καθεμιά:
//   - τα διπλά σύμφωνα: αν προεπιλέγονταν, κάθε σύμφωνο κάθε λέξης θα γινόταν
//     στόχος και το παιδί θα πνιγόταν σε ερωτήσεις που δεν κάνει λάθος
//   - το «ου»: είναι μόνο του στην κλάση του, άρα ΔΕΝ έχει εναλλακτικές και
//     δεν μπορεί να γίνει κενό. Παίζεται μόνο σε συναρμολόγηση, που η μάχη
//     δεν υποστηρίζει ακόμα. Προεπιλεγμένο, έφτιαχνε νεκρούς στόχους.
export const AUTO_CLASSES = ['i', 'o', 'e', 'au', 'eu', 'oi_dia', 'ei_dia', 'ai_dia'];

/**
 * Μπορεί αυτό το γράφημα να γίνει κενό με επιλογές; Χρειάζεται τουλάχιστον
 * μία εναλλακτική — αλλιώς δεν υπάρχει ερώτηση να τεθεί.
 * @param {string} g
 */
export function canBeGap(g) {
  return distractorsFor(g).length > 0;
}

// Δίψηφα που μένουν ενωμένα στον τεμαχισμό (με και χωρίς τόνο). Μαζί και οι
// μορφές με διαλυτικά: το «αϋ» είναι ΜΙΑ μονάδα ορθογραφίας, όπως το «αυ» —
// αλλιώς το κενό θα ζητούσε ένα γράμμα και θα πρόδιδε την απάντηση.
const DIGRAPHS = [
  'ει', 'εί', 'οι', 'οί', 'ου', 'ού', 'αι', 'αί',
  'αυ', 'αύ', 'ευ', 'εύ',
  'αϋ', 'αΰ', 'εϋ', 'εΰ',
  'οϊ', 'οΐ', 'εϊ', 'εΐ', 'αϊ', 'αΐ',
  // Διπλά σύμφωνα: μία μονάδα ορθογραφίας, όχι δύο γράμματα
  'λλ', 'μμ', 'νν', 'ππ', 'ρρ', 'σσ', 'ττ', 'κκ', 'ββ', 'γγ', 'γκ'
];

// Τονισμένο ↔ άτονο (ο τόνος είναι εκτός scope ως άσκηση,
// αλλά τα distractors πρέπει να κληρονομούν τον τόνο του στόχου).
// Τα ΐ/ΰ κουβαλούν ΚΑΙ τόνο ΚΑΙ διαλυτικά. Το stripAccent βγάζει μόνο τον
// τόνο και κρατά τα διαλυτικά — είναι δύο διαφορετικά σημάδια και μόνο το
// ένα είναι εκτός scope ως άσκηση.
const ACCENT = {
  'ά': 'α', 'έ': 'ε', 'ή': 'η', 'ί': 'ι', 'ό': 'ο', 'ύ': 'υ', 'ώ': 'ω',
  'ΐ': 'ϊ', 'ΰ': 'ϋ'
};
const ACCENT_REV = {
  'α': 'ά', 'ε': 'έ', 'η': 'ή', 'ι': 'ί', 'ο': 'ό', 'υ': 'ύ', 'ω': 'ώ',
  'ϊ': 'ΐ', 'ϋ': 'ΰ'
};

export function stripAccent(g) {
  return [...g].map((c) => ACCENT[c] || c).join('');
}

function hasAccent(g) {
  return [...g].some((c) => c in ACCENT);
}

// Βάζει τόνο σε γράφημα: σε δίψηφο, στο δεύτερο γράμμα (εί, οί, ού, αί, οΐ).
function addAccent(g) {
  const chars = [...g];
  const i = chars.length - 1;
  if (ACCENT_REV[chars[i]]) chars[i] = ACCENT_REV[chars[i]];
  return chars.join('');
}

// Τεμαχισμός λέξης σε γραφήματα (greedy, δίψηφα πρώτα).
export function splitGraphemes(text) {
  const units = [];
  let i = 0;
  while (i < text.length) {
    const two = text.substr(i, 2);
    if (DIGRAPHS.includes(two)) { units.push(two); i += 2; }
    else { units.push(text[i]); i += 1; }
  }
  return units;
}

// Κλάση σύγχυσης για γράφημα (αγνοώντας τόνο) — null αν δεν ανήκει σε καμία.
export function classForGrapheme(g) {
  const plain = stripAccent(g);
  for (const [name, members] of Object.entries(CONFUSION_CLASSES)) {
    if (members.includes(plain)) return name;
  }
  return null;
}

// Distractors: τα υπόλοιπα μέλη της κλάσης, με τον τόνο του στόχου.
export function distractorsFor(g) {
  const cls = classForGrapheme(g);
  if (!cls) return [];
  const plain = stripAccent(g);
  const accented = hasAccent(g);
  return CONFUSION_CLASSES[cls]
    .filter((m) => m !== plain)
    .map((m) => (accented ? addAccent(m) : m));
}
